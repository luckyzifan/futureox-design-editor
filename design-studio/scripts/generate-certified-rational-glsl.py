#!/usr/bin/env python3
"""Generate only the integer Q48 enclosure helper; leave existing shaders alone."""
import argparse
import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('rational_generator', Path(__file__).with_name('generate-rational-glsl.py'))
generator = importlib.util.module_from_spec(spec)
spec.loader.exec_module(generator)
source = ROOT / 'design-studio/crates/design-kernel/shaders/certified-rational.wgsl'
destination = ROOT / 'frontend/design-client/src/kernel/gpu/certified-rational.glsl'
expected = '// Generated by design-studio/scripts/generate-certified-rational-glsl.py.\nuint cfSelect(uint a,uint b,bool s){return s?b:a;}\nint cfSelect(int a,int b,bool s){return s?b:a;}\n' + generator.translate(source.read_text()).replace('rfSelect(', 'cfSelect(')
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if destination.read_text() != expected:
        raise SystemExit('Generated Q48 GLSL is stale')
else:
    destination.write_text(expected)
print('Certified rational WGSL/GLSL helpers match')
