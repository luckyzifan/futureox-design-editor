#!/usr/bin/env python3
"""Generate the deliberately restricted integer filter program for WebGL2.

This is not a general WGSL transpiler. Unsupported constructs fail closed;
hardware oracle tests cover the generated production helper independently.
"""
import argparse
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[2]
SOURCE=ROOT/'design-studio/crates/design-kernel/shaders/rational-filter.wgsl'
DEST=ROOT/'frontend/design-client/src/kernel/gpu/rational-filter.glsl'

def translate(source):
    kinds={'u32':'uint','i32':'int','f32':'float','bool':'bool',
           'vec2<u32>':'uvec2','vec3<u32>':'uvec3','vec4<u32>':'uvec4','vec2<i32>':'ivec2',
           'vec2<f32>':'vec2','vec3<f32>':'vec3','vec4<f32>':'vec4',
           'texture_2d<f32>':'highp sampler2D'}
    def parameter(p):
        name,kind=p.split(':');return kinds[kind]+' '+name
    source=re.sub(r'fn (\w+)\(([^)]*)\)->([^\s{]+)',lambda m:kinds[m[3]]+' '+m[1]+'('+','.join(parameter(p)for p in m[2].split(','))+')',source)
    source=re.sub(r'var(?:<private>)? (\w+):array<u32,(\d+)>;',r'uint \1[\2];',source)
    source=re.sub(r'\b(?:let|var) (\w+):([^=;]+)',lambda m:kinds[m[2]]+' '+m[1],source)
    source=source.replace('bitcast<u32>','floatBitsToUint').replace('bitcast<f32>','uintBitsToFloat')
    for a,b in sorted(kinds.items(),key=lambda x:-len(x[0])):
        source=re.sub(r'\b'+re.escape(a)+r'\(',b+'(',source)
    source=source.replace('textureLoad(', 'texelFetch(')
    source=source.replace('textureDimensions(', 'textureSize(')
    source=re.sub(r'\bu\(([^()]+)\)',r'u[\1]',source)
    source=source.replace('select(', 'rfSelect(')
    # GLSL comparisons of vectors use named builtins.
    source=source.replace('q<ivec2(0)','lessThan(q,ivec2(0))').replace('q>=ivec2(u[1].zw)','greaterThanEqual(q,ivec2(u[1].zw))').replace('q>=ivec2(u[2].zw)','greaterThanEqual(q,ivec2(u[2].zw))')
    source=re.sub(r'all\(([\w.]+)==(uvec[234]\(0u?\))\)',r'all(equal(\1,\2))',source)
    code=re.sub(r'//[^\n]*','',source)
    if re.search(r'\b(fn|var|let|bitcast|array|u32|i32|f32)\b',code):raise ValueError('Untranslated construct')
    return source

def generate():
    return '// Generated by design-studio/scripts/generate-rational-glsl.py.\nuint rfSelect(uint a,uint b,bool s){return s?b:a;}\nint rfSelect(int a,int b,bool s){return s?b:a;}\n'+translate(SOURCE.read_text())

def replace_block(text,label,body):
    start='// BEGIN GENERATED '+label+'\n'
    end='// END GENERATED '+label
    if text.count(start)!=1 or text.count(end)!=1:
        raise ValueError('Missing or ambiguous generated marker: '+label)
    before,rest=text.split(start,1)
    _,after=rest.split(end,1)
    return before+start+body+end+after

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    outputs={DEST:generate()}
    wgsl=(ROOT/'design-studio/crates/design-kernel/shaders/vector.wgsl').read_text()
    vector=ROOT/'frontend/design-client/src/kernel/gpu/vector.glsl';text=vector.read_text()
    source=wgsl.split('// BEGIN GENERATED MATERIAL MATH SOURCE\n',1)[1].split('// END GENERATED MATERIAL MATH SOURCE',1)[0]
    text=replace_block(text,'MATERIAL MATH','uint materialSelect(uint a,uint b,bool s){return s?b:a;}\n'+translate(source).replace('rfSelect(', 'materialSelect('))
    source=wgsl.split('// BEGIN GENERATED BLEND MATH SOURCE\n',1)[1].split('// END GENERATED BLEND MATH SOURCE',1)[0]
    text=replace_block(text,'BLEND MATH',translate(source))
    source=wgsl[wgsl.index('fn blendRN('):wgsl.index('fn fixedLinear(')]
    for name,kind in [('cb','vec3<f32>'),('cs','vec3<f32>'),('components','vec3<f32>'),('m','vec4<f32>'),('left','vec4<f32>'),('middle','vec4<f32>'),('right','vec4<f32>'),('rgb','vec4<f32>')]:
        source=re.sub(r'\b(let|var) '+name+'=',r'\1 '+name+':'+kind+'=',source)
    text=replace_block(text,'BLEND COMPOSITE',translate(source));outputs[vector]=text
    for name in ['coverage64','area']:
        source=(ROOT/f'design-studio/crates/design-kernel/shaders/{name}.wgsl').read_text()
        prelude='uint rfSelect(uint a,uint b,bool s){return s?b:a;}\n' if name=='coverage64' else ''
        outputs[ROOT/f'frontend/design-client/src/kernel/gpu/{name}.glsl']='// Generated by design-studio/scripts/generate-rational-glsl.py.\n'+prelude+translate(source)
    # Construct and validate every output before changing any generated file.
    for path,expected in outputs.items():
        if args.check and path.read_text()!=expected:raise SystemExit('Generated GLSL is stale: '+str(path))
    if not args.check:
        for path,expected in outputs.items():path.write_text(expected)
    print('Filter, material, blend and coverage GLSL match the shared programs')
