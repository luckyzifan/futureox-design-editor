import { afterEach, expect, test, vi } from 'vitest'
afterEach(() => { vi.unstubAllGlobals(); vi.restoreAllMocks(); vi.useRealTimers(); vi.resetModules() })
test('document phases are paired numeric records and never capture raw document/error content', async () => {
  vi.useFakeTimers(); vi.stubGlobal('window', { coreDesktop: { renderDiagnostics: true, renderDiagnosticsDetail: true } })
  const log = vi.spyOn(console, 'log').mockImplementation(() => {})
  const { documentStage, documentStageAsync, DocumentStage } = await import('./document-lifecycle-diagnostics')
  expect(documentStage(DocumentStage.admission, () => 'PRIVATE DOCUMENT CONTENT', 123)).toBe('PRIVATE DOCUMENT CONTENT')
  await expect(documentStageAsync(DocumentStage.decode, async () => { throw new Error('PRIVATE ERROR CONTENT') }, 456)).rejects.toThrow('PRIVATE ERROR CONTENT')
  await vi.runAllTimersAsync()
  const lines = log.mock.calls.map(([line]) => String(line)), rows = lines.flatMap(line => JSON.parse(line.slice('[render-diag] '.length)).batch)
  expect(rows).toHaveLength(4); expect(rows.map(r => r.methodCode)).toEqual([203, 203, 202, 202])
  expect(rows.map(r => r.phase)).toEqual([1, 2, 1, 2]); expect(rows.map(r => r.reasonCode)).toEqual([0, 1, 0, 2])
  expect(rows[0].count).toBe(rows[1].count); expect(rows[2].count).toBe(rows[3].count)
  expect(lines.join('')).not.toContain('PRIVATE'); expect(rows.map(r => r.sourceCodeUnits)).toEqual([123, 123, 456, 456])
})
test('disabled diagnostics do not allocate a journal timer or emit content', async () => {
  vi.useFakeTimers(); const log = vi.spyOn(console, 'log').mockImplementation(() => {})
  const { documentStage, DocumentStage } = await import('./document-lifecycle-diagnostics')
  expect(documentStage(DocumentStage.prepare, () => 7)).toBe(7)
  expect(vi.getTimerCount()).toBe(0); expect(log).not.toHaveBeenCalled()
})
