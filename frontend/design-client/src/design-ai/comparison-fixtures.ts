const SEARCH_ROOTS = [
  process.env.FUTUREOX_COMPARE_DIR,
  '/cursor/stores/self/compare-fixtures',
  '/cursor/stores/bot/compare-fixtures',
].filter((root): root is string => !!root)

function walk(dir: string, into: string[], depth = 0) {
  if (depth > 6) return
  let entries: string[]
  try { entries = readdirSync(dir) } catch { return }
  for (const name of entries) {
    const path = join(dir, name)
    let info
    try { info = statSync(path) } catch { continue }
    if (info.isDirectory()) walk(path, into, depth + 1)
    else if (/\.(fig|sketch)$/i.test(name) && info.size > 0 && info.size < 100 * 1024 * 1024) into.push(path)
  }
}

/** Real files only. Missing Downloads names stay absent instead of being replaced by generated bytes. */
export function availableCompareFiles(extraRoots: string[] = []) {
  const files: string[] = []
  for (const root of [...SEARCH_ROOTS, ...extraRoots]) walk(root, files)
  const byName = new Map<string, string>()
  for (const path of files) if (!byName.has(basename(path))) byName.set(basename(path), path)
  const found: { name: string; path: string }[] = []
  for (const name of EXPECTED_COMPARE_NAMES) {
    const path = byName.get(basename(name))
    if (path) found.push({ name, path })
  }
  return found
}

export function missingCompareNames(found: { name: string }[]) {
  const present = new Set(found.map(file => basename(file.name)))
  return EXPECTED_COMPARE_NAMES.filter(name => !present.has(basename(name)))
}

export function readCompareFile(path: string) {
  return new Uint8Array(readFileSync(path))
}
