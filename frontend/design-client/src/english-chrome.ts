export function presentChrome(source: string, locale: InterfaceLocale = 'zh-CN', depth = 0): string {
  if (locale !== 'en' || depth > 4 || typeof source !== 'string' || source.length === 0) return source
  if (Object.prototype.hasOwnProperty.call(phrases, source)) return phrases[source]
  for (const { pattern, format } of patterns) {
    const match = pattern.exec(source)
    if (match) return format(match.slice(1))
  }
  return source
}
